import React from 'react';

export type IconProps = React.SVGProps<SVGSVGElement> & { size?: number | string };

const createIcon = (svgContent: React.ReactNode, defaultSize = 18) => {
  return (props: IconProps) => {
    const { size, width, height, style, className, ...rest } = props;
    const finalWidth = width ?? size ?? defaultSize;
    const finalHeight = height ?? size ?? defaultSize;

    return (
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth="2"
        strokeLinecap="round"
        strokeLinejoin="round"
        width={finalWidth}
        height={finalHeight}
        className={className}
        style={{
          display: 'inline-block',
          verticalAlign: 'middle',
          flexShrink: 0,
          width: typeof finalWidth === 'number' ? `${finalWidth}px` : finalWidth,
          height: typeof finalHeight === 'number' ? `${finalHeight}px` : finalHeight,
          maxWidth: typeof finalWidth === 'number' ? `${finalWidth}px` : finalWidth,
          maxHeight: typeof finalHeight === 'number' ? `${finalHeight}px` : finalHeight,
          ...style,
        }}
        {...rest}
      >
        {svgContent}
      </svg>
    );
  };
};

